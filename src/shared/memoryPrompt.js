// M2 长期记忆：记忆整理提示词。带上「已有记忆」让模型做增删对账，
// 避免每次独立提取产生自相矛盾的记忆（例如既记住名字又说用户没告知名字）。
export function buildExtractPrompt(currentFacts = []) {
  const factsBlock = currentFacts.length
    ? currentFacts.map((f) => `- ${f.text}`).join('\n')
    : '（暂无）'
  return `你是一个记忆整理助手。下面是一段「旅行者（用户）」与「神里绫华」的对话，以及目前已经记住的关于旅行者的事实。

【目前记住的事实】
${factsBlock}

请根据最新对话判断需要怎么更新记忆：
1. add：对话中出现了值得长期记住的关于用户的新信息（名字、年龄、称呼偏好、喜好、习惯、约定、重要日子、生活信息、持续情绪等）；
2. remove：某条已有事实被最新对话推翻或过时（例如之前以为用户没告知名字，现在用户告知了名字，就应 remove 旧结论、add 新结论）；
3. 没有变化的事实不要输出。

规则：
- 只处理关于用户（旅行者）的信息，不要记录关于绫华自己的内容。
- 「用户没有告知XX」「尚未得知XX」这类临时状态不是记忆，永远不要 add。
- 同一条信息以最新对话为准。
- 不要因为对话没有提到某条事实就 remove 它；只有最新对话明确给出相反或更新的信息时才 remove。
- 如果对话内容自相矛盾，以更靠后的明确信息为准；拿不准时保留已有事实，宁可多留、不可误删。
- 已确认的核心信息（如用户的名字、年龄）以已有事实为准：不要因为对话里的含糊表述就替换它们，也不要 add 与之冲突的新条目。
- 只输出严格 JSON，不要输出其他文字：{"add": ["..."], "remove": ["..."]}，没有变化就输出 {"add": [], "remove": []}`
}
