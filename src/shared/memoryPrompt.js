// M2 长期记忆：记忆整理提示词（v2 结构化版）。
// 分类 + 冲突规则：身份信息同类只保留最新一条，避免「小明」「小红」并存。
export function buildExtractPrompt(currentFacts = []) {
  const factsBlock = currentFacts.length
    ? currentFacts.map((f) => `- [${f.category || '其他'}] ${f.text}`).join('\n')
    : '（暂无）'
  return `你是一个记忆整理助手。下面是「旅行者（用户）」与「神里绫华」的对话，以及目前已经记住的关于旅行者的事实。

【目前记住的事实】
${factsBlock}

请根据最新对话判断需要怎么更新记忆。记忆分这几类：
- identity 身份信息：名字、称呼、年龄、职业、所在地等——**同一项只保留最新一条**（例如已有「用户叫小明」，用户现在说叫小红，就必须 remove 旧条目、add 新条目，绝不能两条并存）；
- preference 喜好与厌恶；
- date 重要日期与事件（生日、纪念日、约定、计划等）；
- relationship 关系与称呼习惯；
- status 生活状态与情绪（临时情绪只在持续明显时记录）；
- other 其他值得长期记住的。

规则：
1. 只处理关于用户（旅行者）的信息，不要记录关于绫华自己的内容。
2. 「用户没有告知XX」「尚未得知XX」这类临时状态不是记忆，永远不要 add。
3. 不要因为对话没提到某条事实就 remove；只有最新对话明确给出相反或更新的信息时才 remove。
4. 对话自相矛盾时，以更靠后的明确信息为准；拿不准就保留，宁可多留、不可误删。
5. 输出严格 JSON，不要输出其他文字：
{"add": [{"text": "事实文本", "category": "identity"}], "remove": ["旧事实原文"]}
没有变化就输出 {"add": [], "remove": []}`
}
